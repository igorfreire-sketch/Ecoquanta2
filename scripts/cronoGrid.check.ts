import assert from 'node:assert/strict';
import { criarLinhaVazia } from '../src/lib/cronoRow';
import { moverDireita, moverEsquerda, ordemArvore, calcularCodigos, editarPredecessora, salvarColuna, excluirColuna, ordemColunasCronograma } from '../src/lib/cronoGridLogic';
import type { CronogramaDoc } from '../src/components/CronogramaGrid';
const row = (id: string, seq: number) => ({ ...criarLinhaVazia(seq), id });
let rows = [row('a', 1), row('b', 2), row('c', 3)];
rows = moverDireita(rows, 'b'); rows = moverDireita(rows, 'c');
assert.equal(rows.find(r => r.id === 'b')!.parentId, 'a');
assert.equal(rows.find(r => r.id === 'c')!.parentId, 'a');
assert.equal(calcularCodigos(rows).get('c'), '1.3');
assert.deepEqual(ordemArvore(rows.map(r => r.id === 'a' ? { ...r, colapsada: true } : r)).map(r => r.id), ['a']);
rows = moverEsquerda(rows, 'b'); assert.equal(rows.find(r => r.id === 'b')!.parentId, '');
assert.deepEqual(moverDireita(rows, 'a'), rows);
rows[0].dataFim = '2026-11-10';
rows = editarPredecessora(rows, 'b', 'a');
assert.equal(rows.find(r => r.id === 'b')!.dataInicio, '2026-11-10');
assert.deepEqual(editarPredecessora(rows, 'a', 'b'), rows);
assert.deepEqual(editarPredecessora(rows, 'a', 'a'), rows);
let doc = { rows, colunasCustom: [], colOrder: ['nome', 'custom'], colWidths: {} } as unknown as CronogramaDoc;
doc = salvarColuna(doc, { id: 'custom', nome: 'Detalhe' });
assert.equal(doc.colunasCustom.length, 1);
doc = salvarColuna(doc, { id: 'custom', nome: 'Novo' });
assert.equal(doc.colunasCustom[0].nome, 'Novo');
doc.rows[0].custom = { custom: 'valor', other: 'preservado' };
assert.equal(ordemColunasCronograma(doc)[1], 'custom');
doc = excluirColuna(doc, 'custom');
assert.equal(doc.colunasCustom.length, 0); assert.equal(doc.rows[0].custom!.custom, undefined);
assert.equal(doc.rows[0].custom!.other, 'preservado'); assert.ok(!doc.colOrder!.includes('custom'));
console.log('PASS: indent, outdent, sibling hierarchy, codes, collapse, predecessor guard/dates, column add/rename/remove');
